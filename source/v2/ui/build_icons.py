OUT = Path(sys.argv[1] if len(sys.argv) > 1 else 'public/assets/ui/icons'); OUT.mkdir(parents=True, exist_ok=True)
INK, RIM, LINE, RIM_W = '#2b2622', '#f4efe6', 3, 9
STAMP = '#c4402a'


def icon(name, shapes, details='', top='', defs=''):
    """shapes: list of ('fill', d, colour) or ('stroke', d, colour, width) or ('raw-fill', svg-element-without-style)."""
    rim, fill, outline = [], [], []
    for s in shapes:
        if s[0] == 'fill':
            _, d, c = s
            rim.append(f'<path d="{d}" fill="{RIM}" stroke="{RIM}" stroke-width="{RIM_W}"/>')
            fill.append(f'<path d="{d}" fill="{c}"/>')
            outline.append(f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="{LINE}"/>')
        elif s[0] == 'stroke':
            _, d, c, w = s
            rim.append(f'<path d="{d}" fill="none" stroke="{RIM}" stroke-width="{w + 2 * LINE + RIM_W - LINE}"/>')
            outline.append(f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="{w + 2 * LINE}"/>')
            outline.append(f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}"/>')
        elif s[0] == 'circle':
            _, cx, cy, r, c = s
            rim.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{RIM}" stroke="{RIM}" stroke-width="{RIM_W}"/>')
            fill.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{c}"/>')
            outline.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{INK}" stroke-width="{LINE}"/>')
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">'
           f'<!-- Human Enough! icon family: {name}. Generated by source/v2/ui/build_icons.py -->'
           f'{"<defs>" + defs + "</defs>" if defs else ""}'
           f'<g stroke-linejoin="round" stroke-linecap="round">{"".join(rim)}{"".join(fill)}{details}{"".join(outline)}{top}</g></svg>\n')
    (OUT / f'{name}.svg').write_text(svg)


